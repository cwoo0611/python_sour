# 입력 함수: [사번, 이름, 기본급, 입사년도]
def inputfunc():
    datas = [
        [1, "강나루", 1500000, 2010],
        [2, "이바다", 2200000, 2018],
        [3, "박하늘", 3200000, 2005],
    ]
    return datas


def processfunc(datas):
    올해 = 2026

    print('사번  이름   기본급   근속연수  근속수당    공제액     수령액')
    print('-' * 60)

    for row in datas:
        사번, 이름, 기본급, 입사년도 = row
        근속연수 = 올해 - 입사년도

        # 근속수당 계산
        if 근속연수 <= 3:
            근속수당 = 150000
        elif 근속연수 <= 8:
            근속수당 = 450000
        else:
            근속수당 = 1000000

        급여액 = 기본급 + 근속수당

        # 공제세율 계산
        if 급여액 >= 3000000:
            공제세율 = 0.5
        elif 급여액 >= 2000000:
            공제세율 = 0.3
        else:
            공제세율 = 0.15

        공제액 = int(급여액 * 공제세율)
        수령액 = 급여액 - 공제액

        print(f'{사번:<4} {이름:<6} {기본급:<10} {근속연수:<8} {근속수당:<10} {공제액:<10} {수령액}')

    print(f'처리 건수 : {len(datas)} 건')


# 실행
datas = inputfunc()
processfunc(datas)